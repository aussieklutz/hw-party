// Regenerates public/weapons.js from the repo's own sources:
//   - engine TAmmoType -> TAmmoStrId table (uVariables.pas AmmozInit, W order)
//   - weapon display names (share/hedgewars/Data/Locale/en.txt "00:<sid>=")
//   - ammo menu order (frontend-qt6/hwconsts.h HW_AMMOMENU_ARRAY, W-space)
// The atlas (Ammos_base.png) cell for weapon W is frame W-1, laid out
// column-major over a 4x16 grid of 32px cells (see uRenderUtils.pas
// GetSurfaceFrameCoordinateX/Y), and the ammo-store string char for W sits at
// 0-based index W-1 (see uAmmos.pas FillAmmoStore: ammoLoadout[ord(a)]).
// Usage: node scripts/gen-weapons.mjs   (run from party/, repo root = ..)

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

const pas = readFileSync(join(root, "hedgewars", "uVariables.pas"), "utf8");
const start = pas.indexOf("AmmozInit: array [TAmmoType] of TAmmozRec = (");
const block = pas.slice(start, start + 100000);
const m = block.slice(100).search(/\n\s*\);/);
const ids = block
  .slice(0, 100 + m)
  .matchAll(/\(NameId:\s*(sid\w+)/g)
  .toArray()
  .map((x) => x[1]);
if (ids.length !== 61) throw new Error(`expected 61 AmmozInit entries, got ${ids.length}`);

const en = readFileSync(join(root, "share", "hedgewars", "Data", "Locale", "en.txt"), "utf8");
const names = new Map();
for (const line of en.split("\n")) {
  const mm = line.match(/^00:(\d+)=(.*)$/);
  if (mm) names.set(Number(mm[1]), mm[2].trim());
}

// TAmmoStrId ordinal per sid name (order of declaration in uTypes.pas)
const sidOrd = {};
{
  const ut = readFileSync(join(root, "hedgewars", "uTypes.pas"), "utf8");
  const decl = ut.match(/TAmmoStrId = \(([^)]*)\)/)[1];
  decl
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean)
    .forEach((s, i) => (sidOrd[s] = i));
}

const weapons = [];
for (let w = 1; w < ids.length; w++) {
  const sid = ids[w];
  const sidIdx = sidOrd[sid];
  const name = names.get(sidIdx);
  if (!name) throw new Error(`no en.txt name for 00:${sidIdx} (${sid})`);
  weapons.push({ w, name });
}

const hwconsts = readFileSync(join(root, "frontend-qt6", "hwconsts.h"), "utf8");
const menuBlock = hwconsts.match(/HW_AMMOMENU_ARRAY\s*\\\s*\{([^}]*)\}/)[1];
const menu = menuBlock
  .replace(/\\\s*\n\s*/g, " ")
  .split(",")
  .map((s) => Number(s.trim()))
  .filter((n) => !Number.isNaN(n));

const out = `// GENERATED by scripts/gen-weapons.mjs — do not edit by hand.
// w = engine TAmmoType ordinal (setweap char code, ammo-store index w-1,
// atlas frame w-1 laid out column-major 4x16). Names from en.txt 00:<sid>.
const HW_AMMOMENU = ${JSON.stringify(menu)};
const HW_WEAPONS = ${JSON.stringify(weapons)};
const HW_MENU_COLS = 10;
const HW_MENU_ROWS = 6;
export { HW_AMMOMENU, HW_WEAPONS, HW_MENU_COLS, HW_MENU_ROWS };
`;
writeFileSync(join(root, "party", "public", "weapons.js"), out);
console.log(`wrote ${weapons.length} weapons, menu order ${menu.length} entries`);
